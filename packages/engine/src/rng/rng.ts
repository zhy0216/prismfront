// 确定性伪随机数发生器 —— 框架 §4.3 的落地。
//
// 框架 §4.3 的原文约束，逐条对应到本文件：
//   - 种子由服务端生成并存库，**永不下发客户端**（可预测随机 = 泄露隐藏信息）。
//     → 本模块只认 `RngState`，不认「明文种子」；`createRngState` 之后种子就再无用处。
//       投影层（M7 `project`）要做的是把 `state.rng` 整个抹掉，而不是抹掉某个 seed 字段。
//   - 所有随机来源必须走 `nextInt`，禁用 `Math.random()`。
//     → engine 的 biome.json 用 `noJsRestrictedProperties` 把 `Math.random` 封死了。
//   - 随机结果作为事件下发（`RANDOM_PICK {result: 33}`），客户端只是被告知。
//   - `{seed, deckLists, intents[]}` 三元组即可完整复现一局 → 回放 / 复现 bug / 申诉。
//     → 这要求本文件的输出序列在**任何 JS 运行时上逐位一致**，见下面「跨平台一致性」。
//
// ---------------------------------------------------------------------------
// 算法选型：xoroshiro64**（Blackman & Vigna, 2018）
// ---------------------------------------------------------------------------
// 框架 §4.3 给的是 `interface RngState { s0: number; s1: number; }`，注释里写
// 「xorshift128+ 或 mulberry32」。两个候选都套不进这个结构，理由如下：
//
//   ✗ xorshift128+ 的状态是 **2 个 uint64**。JS 的 number 是 double，做不了 64 位整数
//     运算；要么上 BigInt，要么把每个 uint64 拆成两条 uint32 lane。
//     - 上 BigInt：`JSON.stringify(1n)` **直接抛 TypeError**，状态立刻不再是纯数据，
//       撞死框架 §3.1 与 §13 坑 3，架构 §6.1 第二条测试（序列化往返）当场红。
//     - 拆 lane：状态变成 4 个 number，跟规范写死的 `{s0, s1}` 两字段对不上。
//   ✗ mulberry32 只有 **32 位状态**：周期 2^32 ≈ 4.3e9，且种子空间只有 2^32 —— 一副 30 张
//     牌有 30! ≈ 2.6e32 种洗法，32 位种子最多只能摸到其中 2^32 种。M8 的 fuzz 要跑万局，
//     每局几千次抽取，周期也不宽裕。更直接的问题是：它只需要一个字段，`s1` 会变成死字段。
//
//   ✓ xoroshiro64** 是同一家族（Blackman/Vigna）的 **32 位成员**：状态就是 2 个 uint32，
//     和规范的 `{s0, s1}` 严丝合缝 —— 事实上 `s0` / `s1` 这两个名字正是 xorshift128+ /
//     xoroshiro 参考 C 实现里那两个局部变量的名字，规范给的结构本来就是这一族的形状。
//     周期 2^64 − 1（全部非零状态构成**唯一一条**环），通过 BigCrush / PractRand，
//     `**` scrambler 修掉了 `+` 族低位线性度差的老问题（所以 `nextInt(s, 2)` 也是干净的）。
//     参数取自作者的参考实现 `xoroshiro64starstar.c`：a=26, b=9, c=13，
//     乘数 0x9E3779BB（32 位黄金分割）与 5。
//
// ---------------------------------------------------------------------------
// 跨平台一致性：为什么这份实现在任何 JS 运行时上都输出同一串数
// ---------------------------------------------------------------------------
// 回放能不能复现，全押在这一段上。
//
//   1. `<<` / `>>>` / `^` 由 ECMA-262 定义为「先 ToInt32/ToUint32，再按 32 位取模」，
//      是**精确的整数语义**，不涉及任何浮点舍入，各引擎必须一致。
//   2. 乘法一律走 `Math.imul`，**绝不写 `a * 0x9E3779BB`**。两个 32 位数相乘需要 64 位
//      有效位，而 double 只有 53 位 —— 直接乘会把低 11 位悄悄舍掉，得到的低位随平台
//      浮点实现漂移。`Math.imul` 规范定义为「乘积的低 32 位，按 int32 解释」，无此问题。
//      这是本文件最容易被后人"顺手优化"掉的一行，改了必红（见 __tests__ 的 BigInt 交叉验证）。
//   3. `%` 只作用在 ≤ 2^32 的精确整数上（远小于 2^53），结果精确。
//   4. 存进状态的两个字段一律 `>>> 0` 规范化为**无符号**。位运算天然产生带符号结果
//      （`0x80000000 | 1 === -2147483647`），如果放任，同一个逻辑状态可能序列化成
//      `-2147483647` 或 `2147483649` 两种文本 —— 架构 §6.1 第一条测试比的是
//      `hash(state)`，那就会假红。无符号是本模块的**规范形式**（同 IR §1 原则 1 的思路）。
//
// ---------------------------------------------------------------------------
// 取模偏置：为什么不是 `x % max`
// ---------------------------------------------------------------------------
// 朴素的 `x % max` 会让 `[0, 2^32 mod max)` 这一段值多出现一次。max 小的时候偏置可以
// 忽略（max=3 时是 40 亿分之一），但它随 max 增大而爆炸：max = 3·2^30 时前 1/3 的取值
// 概率高出 33%。本模块不按 max 大小分情况讨论，一律用**拒绝采样**（丢掉参差的尾巴）：
// 只接受落在 `[0, limit)` 的原始字，`limit` 取 ≤ 2^32 的最大 max 整倍数。
//   - 对任意 max ∈ [1, 2^32]，拒绝概率恒 < 1/2，期望消耗 < 2 个原始字。
//   - 代价：一次 `nextInt` 消耗的原始字数**不固定**。这不影响可复现性（同种子 + 同调用
//     序列 = 同消耗），但意味着不能靠「调用了几次 nextInt」反推流走到哪了。
//   - 死循环风险为零：即使有人喂进被篡改的 `{s0:0, s1:0}`（该状态是发生器的不动点，
//     恒返回 0），0 < limit 恒成立，第一次抽取就会被接受。
//
// ---------------------------------------------------------------------------
// 求值顺序即 RNG 推进顺序（IR §5.4「求值顺序，决定 RNG，必须写死」）
// ---------------------------------------------------------------------------
// 本模块只保证「同样的调用序列产出同样的数」。**调用序列本身由求值器决定**，
// 所以 IR §5.4 的五条规则同样是回放正确性的一部分，写在这里备查：
//   1. 一个动作的字段按签名声明顺序求值（IR §1 原则 1 的规范键序就是可审计的求值顺序）。
//   2. `Act[]` 按数组下标升序。
//   3. `cond.and` / `cond.or` 短路 —— 短路会**跳过**右侧分支里的 RNG 消耗。
//   4. `act.when` 只求值命中的那个分支。
//   5. 光环重算与死亡结算**不得消耗 RNG**（它们每步都跑，一旦消耗就无法保证确定性）。
// M4 写求值器时若改了字段遍历顺序，所有历史回放会静默失真 —— 那不是重构，是破坏性变更。

/**
 * RNG 状态（框架 §4.3 原文签名）。
 *
 * **纯数据**：两个字段都是 `[0, 2^32)` 的无符号整数，`JSON.parse(JSON.stringify(rng))`
 * 与原对象逐字段相等（框架 §3.1、§13 坑 3）。不许在这里放 BigInt / Map / class。
 *
 * 不变量：`(s0, s1) !== (0, 0)`。`createRngState` 通过把 `s1` 钉成奇数来结构性保证，
 * 见该函数的说明。
 */
export interface RngState {
  s0: number;
  s1: number;
}

/**
 * `nextInt` 的最小结构约束。
 *
 * 框架 §4.3 写的是 `nextInt(state: GameState, max: number)`，但 engine 的 `state/`
 * 与 `rng/` 是平级模块：让 `rng` 反过来 import `GameState` 会造成循环依赖，
 * 也会把「随机数发生器」和「整个对局状态」焊死。这里只声明真正用到的那一个字段，
 * `GameState` 结构上天然满足它，调用点写法与框架完全一致。
 *
 * `rng` 声明为 `readonly` 是**故意的**：本模块原地改写 `rng.s0` / `rng.s1` 两个字段，
 * 从不整体替换 `state.rng`，所以对属性本身没有写需求 —— 这样连 `readonly rng` 的
 * 状态类型也能直接传进来。
 */
export interface HasRng {
  readonly rng: RngState;
}

/** 2^32。发生器的字宽，也是本文件里所有模运算的模数。 */
const TWO_POW_32 = 0x1_0000_0000;

/** `nextInt` 的 `max` 上限：2^32。原始字就是 32 位的，再大就得拼字，M2 用不上。 */
export const NEXT_INT_MAX_BOUND = TWO_POW_32;

/** 32 位黄金分割常数 ⌊2^32/φ⌋，xoroshiro64** 的 scrambler 乘数。 */
const GOLDEN32 = 0x9e3779bb;

/**
 * 播种用的 4 轮 Feistel 轮常数（黄金分割 + murmur3 的终混常数，只要求互不相同）。
 *
 * 轮数取 4：Feistel 的双射性与轮数、轮函数**无关**（1 轮就是双射），轮数只影响
 * 「相邻种子是否充分打散」。4 轮足以让种子的任意一位翻转都扩散到全部 64 位。
 */
const SEED_ROUND_KEYS = [0x9e3779b9, 0x85ebca6b, 0xc2b2ae35, 0x27d4eb2f] as const;

/** 32 位循环左移。入参可带符号，返回值一律规范化为无符号。 */
function rotl32(x: number, k: number): number {
  return ((x << k) | (x >>> (32 - k))) >>> 0;
}

/**
 * splitmix32 的位混合器：32 → 32，雪崩良好（常数取自 Wellons 的 hash-prospector）。
 *
 * 只在播种时当 Feistel 的轮函数用。Feistel 的双射性不依赖轮函数的任何性质，
 * 这里要的只是「输入翻一位，输出半数位跟着翻」的扩散能力。
 */
function mix32(x: number): number {
  let z = Math.imul(x ^ (x >>> 16), 0x21f0aaad);
  z = Math.imul(z ^ (z >>> 15), 0x735a2d97);
  return (z ^ (z >>> 15)) >>> 0;
}

/**
 * 抽一个原始 32 位字，**原地推进** `rng`。
 *
 * 刻意不导出：所有随机都必须经过 `nextInt` 的拒绝采样，否则偏置会从这里漏出去。
 * 测试要拿原始字时用 `nextInt(state, NEXT_INT_MAX_BOUND)` —— 此时 limit = 2^32，
 * 永不拒绝且 `x % 2^32 === x`，等价于直接调用本函数。
 */
function nextU32(rng: RngState): number {
  const s0 = rng.s0;
  let s1 = rng.s1;

  // result = rotl(s0 * 0x9E3779BB, 5) * 5      —— ** scrambler
  const result = Math.imul(rotl32(Math.imul(s0, GOLDEN32), 5), 5) >>> 0;

  s1 ^= s0;
  rng.s0 = (rotl32(s0, 26) ^ s1 ^ (s1 << 9)) >>> 0; // a = 26, b = 9
  rng.s1 = rotl32(s1, 13); // c = 13

  return result;
}

/**
 * 由种子构造 RNG 状态（框架 §4.3「种子入状态 → 可回放」）。
 *
 * `seed` 必须是安全整数（`Number.isSafeInteger`），负数与超过 2^32 的值都收；
 * 非整数 / NaN / Infinity 一律抛错 —— 确定性代码里静默接受 NaN 只会把 bug 埋进回放。
 *
 * **不要把种子直接填进 `{s0, s1}`**：xoroshiro 这类 LFSR 家族对低熵初态很敏感，
 * 相邻种子会产生高度相关的开局。这里把种子劈成高低两个 32 位半，走 **4 轮 Feistel**
 * （轮函数是 splitmix32 的位混合器 `mix32`）：
 *
 *   - Feistel 结构 `(l, r) → (r, l ^ F(r))` 对**任意**轮函数都是双射，所以整个
 *     53 位种子空间被单射地铺进 64 位状态空间 —— 不存在「两个种子撞成同一条流」的
 *     结构性碰撞。这不只是洁癖：框架 §4.3 把种子定成**隐藏信息**
 *     （「可预测随机 = 泄露隐藏信息」），可达流的数量就是攻击者暴力搜索的上界。
 *     若把种子先折成 32 位再混合，上界会掉到 2^32 —— 对着几个已下发的随机结果
 *     反推种子是可行的。所以 M9 应当生成**满 53 位**的随机整数当种子。
 *   - 4 轮之后种子的任意一位翻转都会扩散到全部 64 位（雪崩），相邻种子彻底无关。
 *
 * 最后 `s1` **强制为奇数**，这一步同时办掉两件事：
 *   1. 排除 `(0, 0)` —— xoroshiro 唯一的禁用状态（不动点，恒输出 0）。
 *      写成 `| 1` 而不是 `if (s0 === 0 && s1 === 0)`，是因为后者是**永远走不到的
 *      分支**（Feistel 输出的 `(0,0)` 需要一个特定的 64 位原像，53 位种子空间未必
 *      够得着），而走不到的分支既测不了，又会在覆盖率里变成噪声。
 *   2. 不损失流质量：xoroshiro64** 的全部非零状态同属一条长 2^64−1 的环，钉死 `s1`
 *      的最低位只是限制了「从环上哪个点起跳」，不改变环本身。
 *      代价是映射从单射退化为**至多 2 对 1**：仅当两个种子的 Feistel 像只差
 *      「右半的第 0 位」时才撞车，随机两个种子撞上的概率约 2^-63。
 */
export function createRngState(seed: number): RngState {
  if (!Number.isSafeInteger(seed)) {
    throw new RangeError(`RNG 种子必须是安全整数（Number.isSafeInteger），收到：${seed}`);
  }
  // 高半：安全整数最多 21 位有效（负种子取补码高位）；低半：ToUint32 已按 2^32 取模。
  // 除以 2^32 是二进制的纯指数移位，对安全整数精确，不引入浮点误差。
  let l = Math.floor(seed / TWO_POW_32) >>> 0;
  let r = seed >>> 0;
  for (const key of SEED_ROUND_KEYS) {
    const mixed = (l ^ mix32((r + key) | 0)) >>> 0;
    l = r;
    r = mixed;
  }

  return { s0: l, s1: (r | 1) >>> 0 };
}

/**
 * 抽一个 `[0, max)` 的整数（**上界开区间**），并**原地推进** `state.rng`（框架 §4.3）。
 *
 * 这是引擎里**唯一**的随机入口：洗牌、`sel.random(n)`、随机目标、随机发现，全部经此。
 * 用拒绝采样消除取模偏置，理由与代价见文件头「取模偏置」一节。
 *
 * `max` 必须是 `[1, 2^32]` 的整数；`max === 1` 恒返回 0（仍消耗一个字，保持调用点的
 * 推进次数与分支无关）。非法 `max` 抛错，且**抛错前不推进状态** —— 参数错误不该污染流。
 *
 * 空集合不是本函数的职责：调用方要先判空再决定要不要抽（IR 的空集合语义），
 * 不要用 `nextInt(state, 0)` 表达「没得选」。
 */
export function nextInt(state: HasRng, max: number): number {
  if (!Number.isInteger(max) || max < 1 || max > NEXT_INT_MAX_BOUND) {
    throw new RangeError(`nextInt 的 max 必须是 1..2^32 的整数，收到：${max}`);
  }

  // limit = ≤ 2^32 的最大 max 整倍数。落在 [limit, 2^32) 的字会让低段取值多占一次，丢弃。
  const limit = TWO_POW_32 - (TWO_POW_32 % max);
  let x = nextU32(state.rng);
  while (x >= limit) {
    x = nextU32(state.rng);
  }
  return x % max;
}
