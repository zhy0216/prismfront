// 空集合语义的**统一表**（IR v1 §5.2）+ 无效槽语义（DSL v2 §3.1）。
//
// ═══════════════════════════════════════════════════════════════════════════
// 为什么是一张表，而不是各 op 自己写字面量
// ═══════════════════════════════════════════════════════════════════════════
// IR v1 §5.2 的标题原文就是「空集合语义（**统一规则，不许各 op 各自发明**）」。
// 所以这里是全引擎唯一写下这些取值的地方：`eval/` 的每个 op 都从 {@link EMPTY_SET}
// 取值，**不写字面 `0` / `-1` / `true` / `false`**。
// 收益是双向的 —— 改一处全部 op 跟着改；而某个 op 想「就这次特殊一下」，
// 必须先动这张表，动不了就说明它本来就不该特殊。
//
// 全称量化那一条更进一步：所有 `cond.has_*` / `cond.is_*` 一律经过
// {@link forAll}，空集判定只在那一个函数里发生（见该函数的说明）。
//
// ═══════════════════════════════════════════════════════════════════════════
// IR v1 §5.2 原文表（逐条抄下）
// ═══════════════════════════════════════════════════════════════════════════
// | 位置                        | 空集合行为                                    |
// |-----------------------------|-----------------------------------------------|
// | `act.*` 的 target / player  | **静默跳过**，不报错，不产生事件              |
// | `num.count`                 | `0`                                           |
// | `num.attr` / `num.sum`      | `0`                                           |
// | `cond.exists`               | `false`                                       |
// | `cond.has_*` / `cond.is_*`  | `true`（全称量化，见 §3.3 注意）              |
// | `card.of` / `card.random`   | 整个动作跳过                                  |
//
// 规范原话：「"造成 6 点伤害"打空气不该崩，也不该记事件。这条统一了，
// 卡牌脚本里就不用到处写守卫。」
//
// ═══════════════════════════════════════════════════════════════════════════
// ★ 全 IR 唯一的例外：`num.slot_index` → `-1`（DSL v2 §3.3）★
// ═══════════════════════════════════════════════════════════════════════════
// 它**不能**跟着 `num.count` 一起回 0 —— **0 是一个真实格子**，拿来当空值用会让
// 「站在 0 号格」与「根本不在场」变成同一件事。整份 IR 里只有这一个数值位不回 0，
// 所以它在表里单列一行，并在 `num.ts` 的 `num.slot_index` 分支上再点一次名。
//
// ═══════════════════════════════════════════════════════════════════════════
// 无效槽语义 = 空集合语义的位置版（DSL v2 §3.1）
// ═══════════════════════════════════════════════════════════════════════════
// 动作的 SlotRef 解析为无效槽 → 该动作**静默跳过**；`cond.occupied(无效槽)` → `false`。
// 求值器用 `null`（{@link INVALID_SLOT}）表示无效槽，与「取不到值」的其它位一致；
// 判空一律写 `=== null`，**不要**用真值判断 —— `{player:0,index:0}` 是合法格位，
// 而 0 号格恰恰是最常被写进卡牌的那一格。

/**
 * 空集合语义统一表（IR v1 §5.2 + DSL v2 §3.3 的唯一例外）。
 *
 * 键名按「哪个位」而不是「哪个 op」取：同一个取值服务多个 op 时不重复列。
 */
export const EMPTY_SET = {
  /**
   * `act.*` 的 target / player 求值为空集 → 整个动作**静默跳过**，
   * 不报错、不产生事件。动作层的落地在 `handlers/`（E4），本常量是它的取值来源。
   */
  actSkipped: null,
  /** `num.count`：集合大小，空集自然为 0（这一行是它的规范依据）。 */
  count: 0,
  /** `num.attr`：空集，以及「集合非单元素」这一情形（IR v1 §3.2）。 */
  attr: 0,
  /** `num.sum`：求和的单位元。 */
  sum: 0,
  /**
   * ★ `num.slot_index`：**全 IR 唯一的例外**（DSL v2 §3.3）。
   * 不在场 / 非单实体 → `-1`，因为 0 是真实格子，不能当空值用。
   */
  slotIndex: -1,
  /** `cond.exists`：空集恒假（`atLeast` 默认 1）。 */
  exists: false,
  /**
   * `cond.has_*` / `cond.is_*`：**全称量化**，空集恒真（数学惯例，IR v1 §3.3 注意）。
   * 要表达「存在一个 X」必须写 `cond.exists(sel.where(of, X))`，
   * 这是整份规范最容易写错的一处。判定统一走 {@link forAll}。
   */
  all: true,
  /** `card.of` / `card.random` 求值为空 → 整个动作跳过（IR v1 §5.2 末行，E4 落地）。 */
  cardRef: null,
} as const;

/** 无效槽（DSL v2 §3.1）。`evalSlot` 的失败返回值，判空一律 `=== null`。 */
export const INVALID_SLOT = null;

/**
 * **全称量化**：`list` 中每个成员都满足 `pred` 才为真；**空集恒真**（IR v1 §5.2）。
 *
 * 全部 `cond.has_*` / `cond.is_*` 都从这里过 —— 于是「空集 → true」这条最容易写错的
 * 规则在整个引擎里只有**一处**实现，新加一个全称量化的 cond op 也不可能忘掉它。
 *
 * 刻意不直接写 `list.every(pred)`（它对空数组同样返回 `true`）：那样取值就来自
 * `Array.prototype.every` 的语义，而不是来自 {@link EMPTY_SET}，这张表就白立了。
 */
export function forAll<T>(list: readonly T[], pred: (item: T) => boolean): boolean {
  if (list.length === 0) {
    return EMPTY_SET.all;
  }
  return list.every(pred);
}
