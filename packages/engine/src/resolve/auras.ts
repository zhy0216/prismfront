// 流水线第 6 步：光环重算（框架 §4.1 的 `refreshAuras(state)`）。
// 来源：框架 §4.1 时序规则 4、IR v1 §4.3（Aura）、IR v1 §2.3（Enchantment 的 mods/flags）、
//       `state/entity.ts`（`base`/`tags`、`baseFlags`/`flags` 的分工）。
//
// ═══════════════════════════════════════════════════════════════════════════
// 时序规则 4（框架 §4.1 原文）
// ═══════════════════════════════════════════════════════════════════════════
// > **光环是重算而非增量**：`tags = base + 所有附魔 + 所有生效光环`，每步重算。
// > 实体数量在 20 量级，重算成本可忽略，但省掉了「光环失效时忘了减回去」这一整类 bug。
//
// ═══════════════════════════════════════════════════════════════════════════
// ★★ 这条规则对 handler 的强制要求：**持久的属性变更写 `base`，不要写 `tags`** ★★
// ═══════════════════════════════════════════════════════════════════════════
// `tags` 是**派生值**，每一步都会被本函数从 `base` 重新算出来并整体覆盖。
// 往 `tags` 里写东西 = 写进一个下一行就会被抹掉的缓存。
// 症状极具迷惑性：单步测试全绿（因为断言发生在重算之前），一进真实结算就"buff 没了"、
// "召唤出来的单位立刻死了（血量被重算回 0）"。
//
// 各类写入的正确落点：
//   - 召唤/生成实体的初值        → 写 `base`（与 `baseFlags`），再由本函数派生出 `tags`
//   - 附魔（`act.buff`）         → 挂进 `entity.enchantments`，由本函数**加**出来
//   - 光环（`Aura`）             → 不落在实体上，每次由本函数从光环源现算
//   - 伤害与治疗                 → 写 `entity.damage`，**不动 `tags.health`**
//                                 （血量记账见 `state/entity.ts`：当前血量 = tags.health - damage）
//   - `act.set_tag` / `act.mod_tag` 究竟写 `base` 还是转成一条永久附魔，
//     是 M4/M5 的定夺（它决定这类改动扛不扛得住 `act.silence`）。M2 不预先替它选。
//
// ═══════════════════════════════════════════════════════════════════════════
// M2 的实现状态
// ═══════════════════════════════════════════════════════════════════════════
// 恒等实现，但**语义是完整的**：`tags = base + Σ附魔.mods + Σ生效光环.mods`，
// 而 M2 既没有卡表（查不到附魔的 `mods`）也没有光环源，两个 Σ 都是空和 ⇒ `tags = base`。
// 这不是占位符，是规则 4 在"没有任何增益源"这一退化情形下的正确结果，
// 所以**不抛 TODO 异常**（抛了会让 M2 的走查跑不通）。
//
// M5 往里填什么（流水线不需要改）：
//   1. `Σ附魔`：遍历 `entity.enchantments`，按 `ench` 去 bundle 查 `mods` / `flags`
//      （IR v1 §2.3），用 `state/entity.ts` 的 `addTagValues` / `maskWith` 累加；
//      顺带处理 `duration: "while_source_alive"` 的失效剥离（`source` 已不在场）。
//   2. `Σ光环`：枚举光环源实体的 `aura`，求值 `aura.affects`（需要 M4 的求值器）得到
//      受影响集合，把 `mods` / `flags` 加上去。
//   3. `aura` 内**不得出现 `*.random`**（IR v1 §5.4 规则 5，L3 已在编写期校验）——
//      光环每步重算，一旦消耗 RNG，随机流的推进次数会随盘面细节漂移，回放立刻对不上。
//      因此本文件**不 import `../rng`**，一次 `nextInt` 都不调。
//   4. 是否为属性变化补发 `buffed` 事件由 M5 定：规则 4 是"重算"，重算本身不是一件
//      "发生过的事"，给每次重算都发事件会把事件流淹掉。M2 一个事件都不发。

import type { GameState } from "../state/index.ts";
import { createTagValues } from "../state/index.ts";

/**
 * 重算全部实体的派生属性与派生标志位（框架 §4.1 第 6 步）。
 *
 * **重算而非增量**：直接用 `base` / `baseFlags` 覆盖，而不是"把上一次加的减回去"。
 * 这正是规则 4 想消灭的那类 bug 的根源 —— 没有增量，就没有"忘了减回去"。
 *
 * 遍历**全部**实体而不只是场上的：手牌里的牌也会被光环改（费用修正是最常见的一种，
 * IR v1 §10.4 的谜之勇士就是），漏掉手牌等于漏掉一整类卡。
 * 实体量级在几十，成本可忽略（框架 §4.1 原话）。
 *
 * 遍历顺序 = `entities` 的整数键升序（JS 对整数键属性的枚举顺序有规范保证），
 * 与 JSON 往返前后一致。M2 的重算逐实体独立、顺序无关；M5 若引入"光环叠加光环"
 * 这类顺序敏感的算法，要在这里补一句顺序约定。
 */
export function refreshAuras(state: GameState): void {
  for (const entity of Object.values(state.entities)) {
    // tags = base + Σ附魔.mods + Σ生效光环.mods（M5 补两个 Σ）
    entity.tags = createTagValues(entity.base);
    // flags = baseFlags + Σ附魔.flags + Σ生效光环.flags（M5 补两个 Σ）
    entity.flags = entity.baseFlags;
  }
}
