// §6 给它的标注是「边界，红解牌锚点，监控」：+2 已经贴着「偏差 ≤±2 合规」的上沿，
// 而 §4 价格表的「伤害（限单位）4/伤」这一行又以它为换算示例（1 费 ≈ 3 伤）。
// 换句话说这张卡与那一行价格是**互为定义**的，改一边必须同时改另一边。
//
// ═══════════════════════════════════════════════════════════════════════════
// ★「限单位」落在 `script.target` 的**目标域**上，不是在 act 里判 ★
// ═══════════════════════════════════════════════════════════════════════════
// `ALL_UNITS` = `sel.zone(both, "board")` —— 战线上的全部实体（v2.1 §11.2 之后含英雄）。
// 基地在 `"base"` 区，**不在这个域里**，于是"打不到脸"是选择器的结构性结果：
// 目标域怎么写，客户端的高亮、bot 的候选枚举、L3 校验读到的就是同一件事。
// 换成"域给全体、`act.hit` 里再判一下不是基地"会有两个真相源，且客户端只能靠猜。
//
// 与 R09 火球术的唯一区别就是这个域（`ANY_CHARACTER` 多含 `"base"`），
// §4 价格表也正是按这一条把两者分成 4/伤 与 4.5/伤 两行。
//
// 目标域取**双方**单位而不只是敌方：「限单位」限的是**基地**，不是敌我。
// 打自己的单位是合法的（配合 G06 反伤一类的组合），红的解牌不该在这里额外收窄。
